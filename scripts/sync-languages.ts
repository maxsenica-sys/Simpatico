// Regenerates shared/languages.ts from Soniox's supported-language list.
// Run at build time when Soniox adds languages:  SONIOX_API_KEY=... npm run sync-languages
// Adding a language is then a rebuild (plus `npm run translate-ui` for its UI bundle), not a code change.
import { writeFileSync } from "node:fs";
import { LANGUAGES } from "../shared/languages";

const MODEL = process.env.SONIOX_MODEL ?? "stt-rt-v6";
const key = process.env.SONIOX_API_KEY;
if (!key) throw new Error("SONIOX_API_KEY is required");

const res = await fetch("https://api.soniox.com/v1/models", { headers: { Authorization: `Bearer ${key}` } });
if (!res.ok) throw new Error(`Soniox models API: HTTP ${res.status}`);
type Model = { id: string; languages?: { code: string; name: string }[] };
const body = (await res.json()) as { models?: Model[] };
const model = body.models?.find((m) => m.id === MODEL) ?? body.models?.find((m) => m.id.startsWith("stt-rt"));
if (!model?.languages?.length) throw new Error(`No language list for ${MODEL} in response`);

// Keep the autonyms and RTL flags we already have; new languages fall back to the English name
// until someone fills in the native name.
const known = new Map<string, { native: string; rtl?: boolean }>(LANGUAGES.map((l) => [l.code, l]));
const rows = model.languages
  .map((l) => ({ code: l.code, name: l.name, native: known.get(l.code)?.native ?? l.name, rtl: known.get(l.code)?.rtl }))
  .sort((a, b) => a.name.localeCompare(b.name));

const lines = rows.map((r) => `  { code: ${JSON.stringify(r.code)}, name: ${JSON.stringify(r.name)}, native: ${JSON.stringify(r.native)}${r.rtl ? ", rtl: true" : ""} },`);
writeFileSync(
  new URL("../shared/languages.ts", import.meta.url),
  `// Supported languages for transcription + translation.
// GENERATED by scripts/sync-languages.ts from Soniox's model list (${model.id}) — do not edit by hand.
// Every pair is supported for translation, so adding a language here is all that is needed.
// \`name\` is the English name (used in LLM prompts), \`native\` is the autonym (shown to users).

export const LANGUAGES = [
${lines.join("\n")}
] as const satisfies readonly { code: string; name: string; native: string; rtl?: boolean }[];
`,
);
const added = rows.filter((r) => !known.has(r.code)).map((r) => r.code);
console.log(`Wrote ${rows.length} languages for ${model.id}.${added.length ? ` New: ${added.join(", ")}` : ""}`);
